def update_mkdocs_nav(records: list):
    """Updates mkdocs.yaml navigation to include imported writeups cleanly."""
    target_files = [Path("mkdocs.yaml"), Path("mkdocs.yml")]
    updated_any = False

    for yaml_path in target_files:
        if not yaml_path.exists() or yaml_path.is_symlink():
            continue

        log(f"Aggiornamento navigazione in {yaml_path.name}...", "info")
        content = yaml_path.read_text(encoding="utf-8")

        lines = [
            "nav:",
            "  - Home: index.md",
            "  - Writeups CTF:",
            "      - Overview: writeups/index.md",
            '      - "Web & Linux - Infiltrate": writeups/web-linux-infiltrate.md',
            '      - "Linux - Kernel & SUID PrivEsc": writeups/linux-privesc-kernel-suid.md'
        ]

        if records:
            lines.append("      - Archivio Notion:")
            for r in sorted(records, key=lambda x: x["title"].lower()):
                safe_title = r['title'].replace('"', '\\"')
                lines.append(f'          - "{safe_title}": writeups/{r["file"]}')

        lines.append("  - About: about.md")
        nav_block = "\n".join(lines) + "\n"

        if "nav:" in content:
            new_content = re.sub(r'nav:\s*\n.*', nav_block, content, flags=re.DOTALL)
        else:
            new_content = content.rstrip() + "\n\n" + nav_block

        yaml_path.write_text(new_content, encoding="utf-8")
        log(f"Navigazione in {yaml_path.name} sincronizzata con successo.", "success")
        updated_any = True

    if not updated_any:
        log("Nessun file mkdocs.yaml trovato per l'aggiornamento.", "warn")


