#!/usr/bin/env python3
"""
scripts/import_notion.py
========================
Automated parser and importer for Notion exported CTF writeups to MkDocs Material.

Features:
- Extracts .zip exports if present in `./notion_export/`
- Strips 32-hex character UUIDs generated by Notion from filenames and folders
- Normalizes slugs and titles
- Locates, copies, and updates relative image paths to `docs/writeups/assets/<slug>/`
- Normalizes code fences (fixing bad language tags like 'basic' or untagged bash prompts)
- Converts Notion block callouts into MkDocs admonitions
- Rewrites internal markdown cross-links
- Updates `docs/writeups/index.md` and `mkdocs.yaml` navigation
"""

import os
import re
import sys
import shutil
import zipfile
import urllib.parse
from pathlib import Path
import yaml

# ANSI terminal colors for hacker styling output
GREEN = "\033[92m"
CYAN = "\033[96m"
YELLOW = "\033[93m"
RED = "\033[91m"
RESET = "\033[0m"
BOLD = "\033[1m"

NOTION_UUID_PATTERN = re.compile(r'[\s_]+[0-9a-fA-F]{32}$')
CODE_BLOCK_START = re.compile(r'^```(\S*)')

def log(msg, level="info"):
    if level == "info":
        print(f"{GREEN}[+]{RESET} {msg}")
    elif level == "warn":
        print(f"{YELLOW}[!]{RESET} {msg}")
    elif level == "error":
        print(f"{RED}[-]{RESET} {msg}")
    elif level == "success":
        print(f"{GREEN}{BOLD}[✓]{RESET} {msg}")
    elif level == "detail":
        print(f"    {CYAN}↳{RESET} {msg}")


def extract_zips_if_any(source_dir: Path):
    """Checks for .zip archives in source_dir and extracts them."""
    zip_files = list(source_dir.glob("*.zip"))
    for zf in zip_files:
        log(f"Trovato archivio zip: {zf.name}. Estrazione in corso...", "info")
        with zipfile.ZipFile(zf, 'r') as zip_ref:
            zip_ref.extractall(source_dir)
        log(f"Estratto {zf.name}", "success")


def clean_title_and_slug(filename: str):
    """
    Given a file like 'Overpass 3 - Hosting 404ee36546c28095a933f82a4651f254.md',
    returns ('Overpass 3 - Hosting', 'overpass-3-hosting')
    """
    stem = Path(filename).stem
    cleaned_title = NOTION_UUID_PATTERN.sub('', stem).strip()
    
    # Generate clean URL slug
    slug = re.sub(r'[^\w\s-]', '', cleaned_title).strip().lower()
    slug = re.sub(r'[-\s]+', '-', slug)
    if not slug:
        slug = "writeup"
    return cleaned_title, slug


def detect_platform(content: str) -> str:
    """Detects CTF platform from content text."""
    lower = content.lower()
    if "tryhackme.com" in lower or "thm" in lower:
        return "TryHackMe"
    elif "hackthebox.com" in lower or "htb" in lower:
        return "HackTheBox"
    elif "vulnhub" in lower:
        return "VulnHub"
    return "CTF / Lab"


def normalize_code_blocks(content: str) -> str:
    """
    Normalizes code fences:
    - Notion often tags bash commands as 'basic', 'jsx' or leaves them empty.
    - If content contains prompt indicators (kali@, $, sudo, nmap, etc.), tag as bash.
    - Tag 'plain text' as 'text'.
    """
    lines = content.split('\n')
    new_lines = []
    in_block = False
    current_lang = ""
    block_lines = []

    for line in lines:
        if line.startswith('```'):
            if not in_block:
                in_block = True
                current_lang = line[3:].strip()
                block_lines = []
            else:
                in_block = False
                # Process the completed block
                block_content = "\n".join(block_lines)
                first_few_lines = "\n".join(block_lines[:5]).lower()
                
                # Check for bash indicators
                has_bash_indicators = any(x in first_few_lines for x in [
                    "kali@", "root@", "$ sudo", "$ nmap", "$ cat", "$ ffuf", "$ curl",
                    "# whoami", "starting nmap", "uid=", "gid=", "msf exploit("
                ])
                
                if current_lang in ["basic", "jsx", "", "plain text", "txt"]:
                    if has_bash_indicators:
                        current_lang = "bash"
                    elif current_lang == "plain text":
                        current_lang = "text"
                    elif current_lang == "basic":
                        current_lang = "bash"
                    elif not current_lang:
                        current_lang = "text"
                
                new_lines.append(f"```{current_lang}")
                new_lines.extend(block_lines)
                new_lines.append("```")
                current_lang = ""
                block_lines = []
        else:
            if in_block:
                block_lines.append(line)
            else:
                new_lines.append(line)

    # In case of unclosed code fence
    if in_block:
        new_lines.append(f"```{current_lang}")
        new_lines.extend(block_lines)
        new_lines.append("```")

    return "\n".join(new_lines)


def convert_notion_callouts(content: str) -> str:
    """Converts Notion blockquotes/callouts with emojis to MkDocs admonitions."""
    callout_map = {
        "💡": "tip",
        "⚠️": "warning",
        "🚨": "danger",
        "ℹ️": "info",
        "📌": "note",
        "✅": "success"
    }

    lines = content.split('\n')
    out_lines = []
    i = 0
    while i < len(lines):
        line = lines[i]
        matched = False
        for emoji, adm_type in callout_map.items():
            if line.startswith(f"> {emoji}"):
                matched = True
                lead_text = line[len(f"> {emoji}"):].strip()
                out_lines.append(f'!!! {adm_type} "{lead_text}"')
                i += 1
                while i < len(lines) and lines[i].startswith("> "):
                    out_lines.append(f"    {lines[i][2:]}")
                    i += 1
                break
        if not matched:
            out_lines.append(line)
            i += 1

    return "\n".join(out_lines)


def process_images_and_links(
    content: str,
    source_file_dir: Path,
    slug: str,
    assets_dest_dir: Path,
    link_mapping: dict
) -> tuple[str, int]:
    """
    Finds local image references, copies image files to assets_dest_dir / slug,
    and updates markdown image and link paths.
    """
    target_asset_dir = assets_dest_dir / slug
    image_count = 0

    # Pattern for markdown images: ![alt](url)
    md_img_pat = re.compile(r'!\[(.*?)\]\((.*?)\)')

    def replace_image(match):
        nonlocal image_count
        alt = match.group(1)
        raw_path = match.group(2).strip()
        
        # Don't touch external URLs
        if raw_path.startswith(('http://', 'https://', '//', 'data:')):
            return match.group(0)

        decoded_path = urllib.parse.unquote(raw_path)
        
        # Candidate locations on disk
        candidates = [
            source_file_dir / decoded_path,
            source_file_dir.parent / decoded_path,
            source_file_dir / Path(decoded_path).name,
        ]

        found_src = None
        for cand in candidates:
            if cand.is_file():
                found_src = cand
                break
        
        if not found_src:
            # Try searching by basename anywhere in source_file_dir or its subdirs
            base_name = Path(decoded_path).name
            matches = list(source_file_dir.glob(f"**/{base_name}"))
            if matches:
                found_src = matches[0]

        if found_src and found_src.is_file():
            target_asset_dir.mkdir(parents=True, exist_ok=True)
            # Sanitize image filename (replace spaces with hyphens)
            safe_name = re.sub(r'\s+', '-', found_src.name)
            dest_file = target_asset_dir / safe_name
            shutil.copy2(found_src, dest_file)
            image_count += 1
            # Relative path from docs/writeups/<slug>.md to assets/<slug>/<safe_name>
            return f'![{alt}](assets/{slug}/{safe_name})'
        else:
            return match.group(0)

    content = md_img_pat.sub(replace_image, content)

    # Rewrite internal cross-page markdown links: [text](old_notion_file.md)
    md_link_pat = re.compile(r'\[(.*?)\]\((.*?)\)')
    def replace_link(match):
        text = match.group(1)
        url = match.group(2).strip()
        if url.startswith(('http://', 'https://', '#', 'mailto:')):
            return match.group(0)
        
        decoded_url = urllib.parse.unquote(url)
        # Check against link_mapping
        for old_ref, new_slug in link_mapping.items():
            if old_ref in decoded_url or Path(decoded_url).name == old_ref:
                return f'[{text}]({new_slug}.md)'
        return match.group(0)

    content = md_link_pat.sub(replace_link, content)
    return content, image_count


def import_writeups(
    source_dir: Path,
    dest_dir: Path,
    assets_dir: Path,
    update_nav: bool = True
):
    source_dir = Path(source_dir).resolve()
    dest_dir = Path(dest_dir).resolve()
    assets_dir = Path(assets_dir).resolve()

    if not source_dir.exists():
        log(f"Cartella sorgente '{source_dir}' non trovata!", "error")
        return []

    dest_dir.mkdir(parents=True, exist_ok=True)
    assets_dir.mkdir(parents=True, exist_ok=True)

    extract_zips_if_any(source_dir)

    all_md_files = list(source_dir.glob("**/*.md"))
    # Filter out macOS artifacts
    all_md_files = [f for f in all_md_files if "__MACOSX" not in f.parts and not f.name.startswith("._")]

    log(f"Trovati {len(all_md_files)} file Markdown in '{source_dir}'.", "info")

    # Step 1: Precompute file mapping
    # Build map: old_stem_or_filename -> new_slug
    link_mapping = {}
    valid_files = []

    for f in all_md_files:
        clean_title, slug = clean_title_and_slug(f.name)
        # Skip the Notion root container index if named "CTF <hash>.md"
        if clean_title.upper() == "CTF" and len(f.name) > 30:
            continue
        link_mapping[f.name] = slug
        link_mapping[f.stem] = slug
        link_mapping[clean_title] = slug
        valid_files.append((f, clean_title, slug))

    imported_records = []

    # Step 2: Process each writeup
    for f, clean_title, slug in sorted(valid_files, key=lambda x: x[1].lower()):
        log(f"Elaborazione: '{f.name}'", "info")
        log(f"Titolo pulito: '{clean_title}' | File: '{slug}.md'", "detail")

        try:
            content = f.read_text(encoding="utf-8", errors="replace")
        except Exception as e:
            log(f"Errore nella lettura di {f}: {e}", "error")
            continue

        platform = detect_platform(content)

        # Remove Notion H1 if it has hash
        lines = content.split('\n')
        if lines and lines[0].startswith('# '):
            h1_text = lines[0][2:].strip()
            h1_clean = NOTION_UUID_PATTERN.sub('', h1_text).strip()
            lines[0] = f"# {h1_clean}"
            content = '\n'.join(lines)
        else:
            # Prepend H1 if missing
            content = f"# {clean_title}\n\n" + content

        # Process code blocks
        content = normalize_code_blocks(content)

        # Process callouts
        content = convert_notion_callouts(content)

        # Process images and links
        content, img_count = process_images_and_links(
            content=content,
            source_file_dir=f.parent,
            slug=slug,
            assets_dest_dir=assets_dir,
            link_mapping=link_mapping
        )
        if img_count > 0:
            log(f"Copiate {img_count} immagini collegate.", "detail")

        # Add YAML frontmatter
        frontmatter = (
            f"---\n"
            f'title: "{clean_title}"\n'
            f'description: "CTF Writeup per {clean_title} ({platform})"\n'
            f"---\n\n"
        )
        final_content = frontmatter + content

        dest_file = dest_dir / f"{slug}.md"
        dest_file.write_text(final_content, encoding="utf-8")
        log(f"Salvato in {dest_file.relative_to(dest_dir.parent.parent)}", "success")

        imported_records.append({
            "title": clean_title,
            "slug": slug,
            "file": f"{slug}.md",
            "platform": platform,
            "images": img_count
        })

    # Step 3: Update docs/writeups/index.md catalog
    update_writeups_index(dest_dir, imported_records)

    # Step 4: Update mkdocs.yaml nav
    if update_nav:
        update_mkdocs_nav(imported_records)

    log(f"Importazione completata con successo! Totale writeup importati: {len(imported_records)}", "success")
    return imported_records


